    ON survey_participations(verification_code_hash);

CREATE TABLE survey_form_webhook_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id BIGINT NOT NULL,
    participation_id BIGINT,
    external_form_id VARCHAR(255) NOT NULL,
    external_response_id VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE,
    failure_reason VARCHAR(100),
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_survey_form_webhook_receipts_form_response
        UNIQUE (external_form_id, external_response_id),

    CONSTRAINT fk_survey_form_webhook_receipts_survey
        FOREIGN KEY (survey_id)
        REFERENCES surveys (id),

    CONSTRAINT fk_survey_form_webhook_receipts_participation
        FOREIGN KEY (participation_id)
        REFERENCES survey_participations (id)
);

CREATE INDEX idx_survey_form_webhook_receipts_survey_id
    ON survey_form_webhook_receipts(survey_id);

CREATE INDEX idx_survey_form_webhook_receipts_participation_id
    ON survey_form_webhook_receipts(participation_id);
