CREATE TABLE user_auth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider VARCHAR(30) NOT NULL,
    issuer VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    email_at_link VARCHAR(255) NOT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_user_auth_identities_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT uk_user_auth_identity_provider_issuer_subject UNIQUE (provider, issuer, subject)
);

CREATE INDEX idx_user_auth_identities_user_provider ON user_auth_identities(user_id, provider);

INSERT INTO user_auth_identities (user_id, provider, issuer, subject, email_at_link, email_verified, created_at, updated_at)
SELECT id, 'GOOGLE', 'https://accounts.google.com', provider_user_id, email, FALSE, created_at, updated_at
FROM users
WHERE auth_provider = 'GOOGLE' AND provider_user_id IS NOT NULL;
