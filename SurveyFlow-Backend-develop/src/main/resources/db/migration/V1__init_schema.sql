-- =========================================================
-- 3. SURVEYS
-- =========================================================

CREATE TABLE survey_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_survey_categories_name
        UNIQUE (name),

    CONSTRAINT uk_survey_categories_slug
        UNIQUE (slug)
);


CREATE TABLE surveys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    creator_id BIGINT NOT NULL,
    category_id BIGINT,

    title VARCHAR(255) NOT NULL,
    description TEXT,

    research_purpose TEXT,
    participant_instructions TEXT,

    provider VARCHAR(30) NOT NULL,
    external_form_url VARCHAR(1000),

    estimated_duration_seconds INTEGER,
    question_count INTEGER,
    language VARCHAR(16),
    contains_sensitive_questions BOOLEAN NOT NULL DEFAULT FALSE,
    data_usage_notice TEXT,

    reward_credit BIGINT NOT NULL,
    target_response_count INTEGER NOT NULL,
    current_response_count INTEGER NOT NULL DEFAULT 0,

    slot_ttl_seconds INTEGER,

    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',

    published_at TIMESTAMP WITH TIME ZONE,
    deadline TIMESTAMP WITH TIME ZONE,

    lock_version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_surveys_creator
        FOREIGN KEY (creator_id)
        REFERENCES users (id),

    CONSTRAINT fk_surveys_category
        FOREIGN KEY (category_id)
        REFERENCES survey_categories (id)
);


CREATE TABLE survey_verification_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    survey_id BIGINT NOT NULL,
    version INTEGER NOT NULL,
    method VARCHAR(30) NOT NULL,

    min_completion_seconds INTEGER,
    max_completion_seconds INTEGER,
    max_attempts INTEGER NOT NULL DEFAULT 3,

    valid_from TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_until TIMESTAMP WITH TIME ZONE,

    webhook_secret_ref VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_survey_verification_configs_survey_id_version
        UNIQUE (survey_id, version),

    CONSTRAINT fk_survey_verification_configs_survey
        FOREIGN KEY (survey_id)
        REFERENCES surveys (id)
);


CREATE TABLE survey_tags (
