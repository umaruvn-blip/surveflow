-- =========================================================
-- 5. SURVEY PARTICIPATION
--
-- Also provides input for AI Quality Check:
-- started_at + completed_at
-- =========================================================

CREATE TABLE survey_participations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    public_id CHAR(36) NOT NULL,
    survey_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,

    verification_config_version INTEGER NOT NULL,
    reward_credit_snapshot BIGINT NOT NULL,
    eligibility_snapshot JSON,
    verification_code_hash VARCHAR(255),

    status VARCHAR(30) NOT NULL DEFAULT 'RESERVED',

    slot_reserved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    slot_expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE,
    verified_at TIMESTAMP WITH TIME ZONE,
    rejected_at TIMESTAMP WITH TIME ZONE,

    verification_attempt_count INTEGER NOT NULL DEFAULT 0,
    failure_reason VARCHAR(100),
    lock_version BIGINT NOT NULL DEFAULT 0,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_survey_participations_public_id
        UNIQUE (public_id),

    CONSTRAINT fk_survey_participations_survey
        FOREIGN KEY (survey_id)
        REFERENCES surveys (id),

    CONSTRAINT fk_survey_participations_user
        FOREIGN KEY (user_id)
        REFERENCES users (id),

    CONSTRAINT fk_survey_participations_verification_config
        FOREIGN KEY (survey_id, verification_config_version)
        REFERENCES survey_verification_configs (survey_id, version)
);


-- =========================================================
-- 6. AI MATCHING
--
-- Stores the result produced by AI Matching.
--
-- score:
--     Matching score, normally between 0 and 1.
--
-- model_version:
--     Version of the matching algorithm/model.
--
-- explanation:
--     Optional explanation of why the user matched.
-- =========================================================

CREATE TABLE matching_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    survey_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,

    score DECIMAL(5,4) NOT NULL,

    model_version VARCHAR(50),
    explanation TEXT,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_matching_results_survey_user
        UNIQUE (survey_id, user_id),

    CONSTRAINT fk_matching_results_survey
        FOREIGN KEY (survey_id)
        REFERENCES surveys (id),

    CONSTRAINT fk_matching_results_user
        FOREIGN KEY (user_id)
        REFERENCES users (id)
);


-- =========================================================
-- 7. AI QUALITY CHECK
--
-- Current implementation:
--
-- started_at
--      +
-- completed_at
--      ↓
-- completion_seconds
--      ↓
-- AI Quality Check
--      ↓
-- quality score + status
-- =========================================================

CREATE TABLE quality_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    participation_id BIGINT NOT NULL,

    completion_seconds INTEGER,

    score DECIMAL(5,4) NOT NULL,

    status VARCHAR(30) NOT NULL,

    model_version VARCHAR(50),

    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_quality_scores_participation
        UNIQUE (participation_id),

    CONSTRAINT fk_quality_scores_participation
        FOREIGN KEY (participation_id)
        REFERENCES survey_participations (id)
);


