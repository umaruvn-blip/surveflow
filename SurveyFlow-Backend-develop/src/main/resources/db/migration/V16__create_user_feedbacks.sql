-- V16: CREATE USER FEEDBACKS TABLE
-- Thu thập phản hồi, đánh giá và nguồn tiếp cận của người dùng
-- =========================================================

CREATE TABLE user_feedbacks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    rating INT,
    sources VARCHAR(500),
    other_source VARCHAR(255),
    content TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_feedbacks_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_user_feedbacks_created_at ON user_feedbacks(created_at DESC);
CREATE INDEX idx_user_feedbacks_user_id ON user_feedbacks(user_id);
