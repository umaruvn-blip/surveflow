CREATE TABLE credit_packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    credit_amount BIGINT NOT NULL,
    price DECIMAL(12,2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'VND',
    display_order INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_credit_packages_code UNIQUE (code),
    CONSTRAINT ck_credit_packages_credit_amount CHECK (credit_amount > 0),
    CONSTRAINT ck_credit_packages_price CHECK (price >= 0),
    CONSTRAINT ck_credit_packages_display_order CHECK (display_order >= 0)
);

CREATE INDEX idx_credit_packages_is_active ON credit_packages (is_active);

CREATE TABLE subscription_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    billing_period VARCHAR(20) NOT NULL,
    price DECIMAL(12,2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'VND',
    valid_from TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_until TIMESTAMP WITH TIME ZONE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_subscription_prices_plan FOREIGN KEY (plan_id) REFERENCES subscription_plans (id),
    CONSTRAINT uk_subscription_prices_plan_period_start UNIQUE (plan_id, billing_period, valid_from),
    CONSTRAINT ck_subscription_prices_price CHECK (price >= 0),
    CONSTRAINT ck_subscription_prices_validity CHECK (valid_until IS NULL OR valid_until > valid_from)
);

CREATE INDEX idx_subscription_prices_plan_period_active
    ON subscription_prices (plan_id, billing_period, is_active);

CREATE TABLE plan_entitlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    code VARCHAR(50) NOT NULL,
    value_type VARCHAR(20) NOT NULL,
    value_amount BIGINT,
    reset_period VARCHAR(20) NOT NULL DEFAULT 'NONE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_plan_entitlements_plan FOREIGN KEY (plan_id) REFERENCES subscription_plans (id),
    CONSTRAINT uk_plan_entitlements_plan_code UNIQUE (plan_id, code),
    CONSTRAINT ck_plan_entitlements_value_type CHECK (value_type IN ('ENABLED', 'UNLIMITED', 'QUOTA', 'PERCENT')),
    CONSTRAINT ck_plan_entitlements_reset_period CHECK (reset_period IN ('NONE', 'MONTH')),
    CONSTRAINT ck_plan_entitlements_value CHECK (
        (value_type IN ('ENABLED', 'UNLIMITED') AND value_amount IS NULL)
        OR (value_type = 'QUOTA' AND value_amount IS NOT NULL AND value_amount > 0)
        OR (value_type = 'PERCENT' AND value_amount IS NOT NULL AND value_amount BETWEEN 1 AND 100)
    )
);

CREATE INDEX idx_plan_entitlements_plan_id ON plan_entitlements (plan_id);

CREATE TABLE reward_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    reward_type VARCHAR(30) NOT NULL,
    credit_cost BIGINT NOT NULL,
    reward_amount BIGINT,
    reward_unit VARCHAR(20),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reward_catalog_code UNIQUE (code),
    CONSTRAINT ck_reward_catalog_credit_cost CHECK (credit_cost > 0),
    CONSTRAINT ck_reward_catalog_reward_type CHECK (reward_type IN ('PLUS_ACCESS', 'EXTRA_CREDITS', 'VOUCHER', 'GIFT')),
    CONSTRAINT ck_reward_catalog_reward_value CHECK (
        (reward_amount IS NULL AND reward_unit IS NULL)
        OR (reward_amount IS NOT NULL AND reward_amount > 0
            AND reward_unit IS NOT NULL AND reward_unit IN ('DAY', 'CREDIT', 'VND'))
    ),
    CONSTRAINT ck_reward_catalog_display_order CHECK (display_order >= 0)
);

CREATE INDEX idx_reward_catalog_is_active ON reward_catalog (is_active);

